"""Upload orchestration: validate, store, extract, persist.

The order matters. A file is validated completely before any byte is written,
the stored filename is generated by TRACE rather than taken from the upload,
and a file that fails extraction is still recorded so the user can see *why* it
failed instead of the upload silently vanishing.
"""

from __future__ import annotations

import logging
import sqlite3
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import config
from database.repositories import ProjectRepository, SourceRepository
from trace_app.models import ExtractionStatus, new_id
from trace_app.security.authz import Capability, Principal, require
from trace_app.services.extraction_service import (
    ExtractionResult,
    extract_text,
    segments_from_json,
)
from trace_app.utils.file_validation import (
    FileValidationError,
    build_stored_path,
    validate_upload,
)

logger = logging.getLogger(__name__)


@dataclass
class UploadOutcome:
    """What happened to one uploaded file. ``source`` is None when rejected."""

    display_name: str
    accepted: bool
    source: dict[str, Any] | None = None
    message: str = ""
    duplicate_of: str | None = None
    #: True when a previous extraction of these exact bytes was reused
    #: instead of parsing the document again.
    reused_extraction: bool = False

    @property
    def extraction_status(self) -> str | None:
        return (self.source or {}).get("extraction_status")


class DocumentService:
    """Source documents, scoped to one actor.

    The principal is held by the service rather than passed per call, so a
    caller cannot read a source without having stated who is asking. Every
    read of document content checks VIEW_SOURCES; a role without it cannot
    retrieve the text through any method here.
    """

    def __init__(self, connection: sqlite3.Connection, principal: Principal) -> None:
        self._connection = connection
        self._principal = principal
        self._sources = SourceRepository(connection)
        self._projects = ProjectRepository(connection)

    @property
    def principal(self) -> Principal:
        return self._principal

    def can_read_sources(self) -> bool:
        return self._principal.can(Capability.VIEW_SOURCES)

    def can_add_sources(self) -> bool:
        return self._principal.can(Capability.UPLOAD_SOURCES)

    # ----------------------------------------------------------------- read
    def list_sources(self, project_id: str) -> list[dict[str, Any]]:
        require(self._principal, Capability.VIEW_SOURCES, project_id)
        return self._sources.list_for_project(project_id)

    def get_source(self, source_id: str, project_id: str) -> dict[str, Any] | None:
        """Fetch a source, enforcing both the role and project ownership."""
        require(self._principal, Capability.VIEW_SOURCES, project_id)
        return self._sources.get(source_id, project_id)

    def usable_sources(self, project_id: str) -> list[dict[str, Any]]:
        """Sources with extracted text -- the only input to reconstruction."""
        require(self._principal, Capability.VIEW_SOURCES, project_id)
        return self._sources.list_usable_for_project(project_id)

    def source_count(self, project_id: str) -> int:
        """How many sources exist. A count is metadata, not content."""
        return self._sources.count_for_project(project_id)

    # --------------------------------------------------------------- upload
    def upload(
        self, project_id: str, raw_name: str | None, content: bytes
    ) -> UploadOutcome:
        """Validate, store, and extract a single uploaded file.

        Never raises for a bad document -- the outcome carries a user-facing
        message instead, so one rejected file does not abort a batch. An
        access failure *does* raise, because that is not a document problem.
        """
        require(self._principal, Capability.UPLOAD_SOURCES, project_id)

        # 1. Validate before touching the disk.
        try:
            validated = validate_upload(raw_name, content)
        except FileValidationError as exc:
            return UploadOutcome(
                display_name=str(raw_name or "untitled"),
                accepted=False,
                message=str(exc),
            )

        # 2. Reject a byte-identical re-upload rather than duplicating evidence.
        existing = self._sources.find_by_hash(project_id, validated.content_hash)
        if existing is not None:
            return UploadOutcome(
                display_name=validated.display_name,
                accepted=False,
                duplicate_of=existing["id"],
                message=(
                    f"“{validated.display_name}” is identical to a source "
                    f"already in this project ({existing['display_name']}). "
                    "It was not added again."
                ),
            )

        # 3. Write using a filename TRACE generates, never the user's.
        source_id = new_id("src")
        try:
            config.ensure_directories()
            stored_path = build_stored_path(source_id, validated.extension)
            stored_path.write_bytes(content)
        except (FileValidationError, OSError) as exc:
            logger.warning("Could not store upload: %s", exc)
            return UploadOutcome(
                display_name=validated.display_name,
                accepted=False,
                message=(
                    f"“{validated.display_name}” could not be saved. "
                    "Please try again."
                ),
            )

        # 4. Extract -- unless these exact bytes have been parsed before.
        #
        # Identical bytes produce identical text, so a stored extraction is
        # the same answer the parser would give. Reuse is scoped to projects
        # this user already belongs to, so it never crosses a boundary they
        # could not see across anyway. This matters most for large PDFs, where
        # parsing is the slow step and the same specification often lands in
        # several projects.
        cached = self._sources.find_extraction_by_hash(
            validated.content_hash, self._principal.user_id
        )
        reused = False
        if cached is not None:
            result = ExtractionResult(
                status=str(cached["extraction_status"]),
                full_text=str(cached["extracted_text"] or ""),
                segments=segments_from_json(cached.get("segments_json")),
                page_count=cached.get("page_count"),
            )
            reused = True
            logger.info(
                "Reusing a stored extraction for %s", validated.display_name
            )
        else:
            result = extract_text(stored_path, validated.extension)

        try:
            source = self._sources.create(
                project_id=project_id,
                display_name=validated.display_name,
                stored_name=stored_path.name,
                file_type=validated.extension,
                file_size=validated.size_bytes,
                extraction_status=result.status,
                extracted_text=result.full_text or None,
                extraction_error=result.error,
                extraction_notes=(
                    "Text reused from an earlier extraction of an identical "
                    "file." if reused else result.notes_text()
                ),
                segments_json=result.segments_json() if result.segments else None,
                char_count=result.char_count,
                page_count=result.page_count,
                content_hash=validated.content_hash,
                source_id=source_id,
            )
        except sqlite3.Error as exc:
            logger.warning("Could not record source: %s", exc)
            self._remove_file_quietly(stored_path)
            return UploadOutcome(
                display_name=validated.display_name,
                accepted=False,
                message=(
                    f"“{validated.display_name}” could not be recorded in the "
                    "database and was not added."
                ),
            )

        self._projects.touch(project_id)

        if result.succeeded and reused:
            message = (
                f"“{validated.display_name}” was added. Its text had "
                "already been extracted from an identical file, so it was not "
                "parsed again."
            )
        elif result.succeeded:
            message = f"“{validated.display_name}” was added and text extracted."
        else:
            message = result.error or "No text could be extracted from this file."
        return UploadOutcome(
            display_name=validated.display_name,
            accepted=True,
            source=source,
            message=message,
            reused_extraction=reused,
        )

    def upload_many(
        self, project_id: str, files: list[tuple[str | None, bytes]]
    ) -> list[UploadOutcome]:
        return [self.upload(project_id, name, data) for name, data in files]

    # --------------------------------------------------------------- delete
    def delete_source(self, source_id: str, project_id: str) -> tuple[bool, str]:
        """Delete a source and its stored file.

        Refused when handover evidence still cites it, so an evidence trail can
        never be silently broken (spec section 8).
        """
        require(self._principal, Capability.UPLOAD_SOURCES, project_id)
        source = self._sources.get(source_id, project_id)
        if source is None:
            return False, "That source could not be found in this project."

        cited = self._connection.execute(
            "SELECT COUNT(*) AS c FROM evidence WHERE source_id = ?", (source_id,)
        ).fetchone()["c"]
        if cited:
            return False, (
                f"“{source['display_name']}” is cited as evidence by {cited} "
                "handover item(s) and cannot be removed."
            )

        try:
            self._sources.delete(source_id, project_id)
        except sqlite3.Error as exc:
            logger.warning("Could not delete source: %s", exc)
            return False, "That source could not be removed."

        self._remove_file_quietly(config.UPLOAD_DIR / str(source["stored_name"]))
        self._projects.touch(project_id)
        return True, f"“{source['display_name']}” was removed."

    @staticmethod
    def _remove_file_quietly(path: Path) -> None:
        try:
            path.unlink(missing_ok=True)
        except OSError as exc:  # pragma: no cover - filesystem dependent
            logger.warning("Could not delete stored file %s: %s", path, exc)


def extraction_summary(sources: list[dict[str, Any]]) -> dict[str, int]:
    """Counts used by the workspace header. Derived from rows, never invented."""
    summary = {"total": len(sources), "usable": 0, "failed": 0, "no_text": 0}
    for source in sources:
        status = source.get("extraction_status")
        if status in (ExtractionStatus.EXTRACTED, ExtractionStatus.PARTIALLY_EXTRACTED):
            summary["usable"] += 1
        elif status == ExtractionStatus.FAILED:
            summary["failed"] += 1
        elif status == ExtractionStatus.NO_TEXT_EXTRACTED:
            summary["no_text"] += 1
    return summary
