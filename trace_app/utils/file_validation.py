"""Upload validation and safe storage naming.

Three independent checks run before a byte is written to disk:

1. the declared extension is on the allow-list,
2. the size is within the documented ceiling,
3. the leading bytes of the file actually look like the declared type.

The stored filename is generated by TRACE from the source ID, so a
user-supplied name is never used to build a path and traversal is structurally
impossible rather than merely filtered.
"""

from __future__ import annotations

import hashlib
import re
import unicodedata
from dataclasses import dataclass
from pathlib import Path

import config

#: Leading bytes that must be present for each container format.
_PDF_MAGIC = b"%PDF-"
_ZIP_MAGIC = (b"PK\x03\x04", b"PK\x05\x06", b"PK\x07\x08")  # DOCX is a ZIP


class FileValidationError(ValueError):
    """A rejected upload. The message is written to be shown to a user."""


@dataclass(frozen=True)
class ValidatedUpload:
    display_name: str
    extension: str
    size_bytes: int
    content_hash: str


def human_size(num_bytes: int) -> str:
    """Render a byte count compactly, e.g. ``1.4 MB``."""
    size = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            if unit == "B":
                return f"{int(size)} B"
            return f"{size:.1f} {unit}"
        size /= 1024
    return f"{size:.1f} GB"  # pragma: no cover - unreachable


def safe_display_name(raw_name: str | None) -> str:
    """Reduce a user-supplied filename to something safe to store and show.

    Any directory component is discarded; this value is only ever displayed,
    never used to construct a filesystem path.
    """
    if not raw_name:
        return "untitled"
    # Normalise, then drop everything up to the last separator of either kind.
    name = unicodedata.normalize("NFKC", str(raw_name))
    name = name.replace("\\", "/").split("/")[-1]
    name = name.replace("\x00", "")
    # Collapse control characters and anything exotic into underscores.
    name = re.sub(r"[\r\n\t]+", " ", name)
    name = re.sub(r'[<>:"|?*]+', "_", name).strip(" .")
    return (name or "untitled")[:150]


def get_extension(display_name: str) -> str:
    return Path(display_name).suffix.lower().lstrip(".")


def _looks_like_declared_type(content: bytes, extension: str) -> tuple[bool, str]:
    """Check the magic bytes. Returns ``(ok, reason_if_not_ok)``."""
    head = content[:8]
    if extension == "pdf":
        if not head.startswith(_PDF_MAGIC):
            return False, "The file does not start with a PDF header."
        return True, ""
    if extension == "docx":
        if not any(head.startswith(magic) for magic in _ZIP_MAGIC):
            return False, (
                "The file is not a valid DOCX package. Legacy .doc files are "
                "not supported — save the document as .docx and try again."
            )
        return True, ""
    if extension == "txt":
        if b"\x00" in content[:4096]:
            return False, "The file contains binary data, not plain text."
        return True, ""
    return False, f"Unsupported file type: .{extension}"


def validate_upload(raw_name: str | None, content: bytes) -> ValidatedUpload:
    """Validate an uploaded file. Raises ``FileValidationError`` on rejection."""
    display_name = safe_display_name(raw_name)
    extension = get_extension(display_name)

    if extension not in config.ALLOWED_EXTENSIONS:
        allowed = ", ".join(f".{ext}" for ext in config.ALLOWED_EXTENSIONS)
        raise FileValidationError(
            f"“{display_name}” is not a supported file type. Allowed: {allowed}."
        )

    size = len(content)
    if size == 0:
        raise FileValidationError(f"“{display_name}” is empty (0 bytes).")
    if size > config.MAX_UPLOAD_BYTES:
        raise FileValidationError(
            f"“{display_name}” is {human_size(size)}, which is over the "
            f"{config.MAX_UPLOAD_MB} MB limit."
        )

    ok, reason = _looks_like_declared_type(content, extension)
    if not ok:
        raise FileValidationError(f"“{display_name}” could not be accepted. {reason}")

    return ValidatedUpload(
        display_name=display_name,
        extension=extension,
        size_bytes=size,
        content_hash=hashlib.sha256(content).hexdigest(),
    )


def build_stored_path(source_id: str, extension: str) -> Path:
    """Return the path to write to, generated entirely by TRACE.

    The result is asserted to be inside the configured upload directory as a
    defence in depth, even though ``source_id`` is machine-generated.
    """
    if not re.fullmatch(r"[A-Za-z0-9_]+", source_id):
        raise FileValidationError("Invalid source identifier.")
    if extension not in config.ALLOWED_EXTENSIONS:
        raise FileValidationError(f"Unsupported file type: .{extension}")

    upload_dir = config.UPLOAD_DIR.resolve()
    candidate = (upload_dir / f"{source_id}.{extension}").resolve()
    if candidate.parent != upload_dir:
        raise FileValidationError("Refusing to write outside the upload directory.")
    return candidate
